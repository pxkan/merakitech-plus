#!/usr/bin/env python3
"""i18n_appendix.py — regenerate Appendix A of docs/dev/UI_v6.md (the EN/DA string table) from the UI's own string dump.

    zig cc -DMERAKIPLUS_PREVIEW -O2 -o build/merakiplus_preview src/merakiplus.c -lm
    build/merakiplus_preview --dump-strings > build/strings.tsv
    python3 tools/i18n_appendix.py build/strings.tsv            # rewrites the block between the I18N-APPENDIX markers
    python3 tools/i18n_appendix.py build/strings.tsv --check    # exit 1 if the appendix is stale
Python stdlib only.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "dev" / "UI_v6.md"
BEGIN = "<!-- I18N-APPENDIX:BEGIN (generated by tools/i18n_appendix.py — edit STR_TABLE in src/mp/i18n.c, not here) -->"
END = "<!-- I18N-APPENDIX:END -->"
GROUPS = [  # (heading, id-prefix regex) — first match wins
    ("Units (identical in both languages)", r"TX_U_"),
    ("Product, splash and pages", r"TX_(TAGLINE|SPL_|PG_|SEC_|LV_)"),
    ("Settings: row labels (SL), notes (SN) and hints (SH)", r"TX_S[LNH]_"),
    ("Enum names", r"TX_(E_|UL_|O_[A-Z])"),
    ("Phases, error codes and activities", r"TX_(PH_|ERR|A_|E[123]|STEAM_)"),
    ("Guards and toasts", r"TX_[GT]_"),
    ("HOME (ring labels, sub-lines, hold hints, stats, chart)", r"TX_(H_|ST_|C_|R_)"),
    ("Buttons", r"TX_B_"),
    ("SYSTEM: startup / UI choice (BOOT UI, lock reasons, help texts)", r"TX_(BL_|BS_|BH|BN_|X_)"),
    ("Editor", r"TX_D_"),
    ("System actions: switch confirmation, exit reminder, goodbye screen", r"TX_(Y_|SW_)"),
    ("DIAGNOSTICS (labels, values, full-width lines, ABOUT block)", r"TX_(DL_|DV_|DG_|NS_)"),
    ("Power button", r"TX_PW_"),
]


def cell(s):
    s = s.replace("|", "\\|").replace("`", "'")
    return "`%s`" % s if s else ""


def build(tsv):
    rows = []
    for line in tsv.splitlines()[1:]:
        p = line.split("\t")
        if len(p) < 4 or p[0] == "TX_NONE":
            continue
        rows.append(p[:4])
    groups = {g[0]: [] for g in GROUPS}
    groups["Other"] = []
    groups["Console (stdout on exit; ASCII)"] = []
    for r in rows:
        if r[1] == "KCON":
            groups["Console (stdout on exit; ASCII)"].append(r)
            continue
        for h, rx in GROUPS:
            if re.match(rx, r[0]):
                groups[h].append(r)
                break
        else:
            groups["Other"].append(r)
    same = sum(1 for r in rows if r[2] == r[3])
    out = [BEGIN, "",
           "**%d string ids × 2 languages** (%d are the same in EN and DA: units, proper names, technical words and commands). "
           "Class = the field the string is shown in; the self-test measures every classified string in both languages against "
           "the field's pixel budget (`-` = measured in its context by the layout tests). `%%s`/`%%d` are placeholders. Since "
           "v7.0 the text is drawn exactly as written (Title Case / sentence case in English, sentence case in Danish). Source: "
           "`--dump-strings` of the preview build." % (len(rows), same), ""]
    for h in [g[0] for g in GROUPS] + ["Other", "Console (stdout on exit; ASCII)"]:
        if not groups[h]:
            continue
        out += ["", "**%s**" % h, "", "| id | class | EN | DA |", "|---|---|---|---|"]
        out += ["| `%s` | %s | %s | %s |" % (r[0], r[1], cell(r[2]), cell(r[3])) for r in groups[h]]
    out += ["", END]
    return "\n".join(out)


def main(a):
    block = build(pathlib.Path(a[0]).read_text())
    doc = DOC.read_text()
    m = re.search(r"<!-- I18N-APPENDIX:BEGIN.*?-->.*?<!-- I18N-APPENDIX:END -->", doc, re.S)
    if not m:
        sys.exit("markers not found in " + str(DOC))
    new = doc[:m.start()] + block + doc[m.end():]
    if "--check" in a:
        print("appendix: " + ("OK" if new == doc else "STALE"))
        return 0 if new == doc else 1
    DOC.write_text(new)
    print("appendix: rewritten (%d lines)" % block.count("\n"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
