#!/usr/bin/env python3
"""build.py — builds Sim Studio: the Meraki+ UI as WebAssembly (current tree + a "classic" git ref) + the static site.

    python3 sim/studio/build.py [--out build/studio] [--classic-ref c9a8524] [--no-classic]

Output (a self-contained static site, served by sim/studio/serve.py):
    OUT/index.html, *.js, *.css        the viewer (copied from sim/studio/)
    OUT/wasm/current.wasm              src/ of this checkout, built with -DMERAKIPLUS_WASM (src/mp/wasm_hal.c)
    OUT/wasm/classic.wasm              src/ of --classic-ref (default c9a8524 = v6.19), extracted with `git archive`
    OUT/fixtures/config.json, parity_spec.json   the sandbox seed (sim/fixtures)
    OUT/builds.json                    what was built (labels, versions, refs, sizes)

A ref older than the browser build (no MERAKIPLUS_WASM in its src/) is BACKPORTED in the temp dir, without changing a line of
its UI code: the startup and loop body of its main() are copied verbatim into src/mp/main_setup.c + src/mp/main_step.c, its
main() is put under #ifndef MERAKIPLUS_WASM, and this checkout's src/mp/wasm_compat.h + src/mp/wasm_hal.c are added
(see backport()). That works for every ref whose main() has the v6.16+ shape (c9a8524 and later).

Needs zig (0.17.1, the same as ./build.sh) and git. Python 3.8+, stdlib only. Never touches a device.
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import io
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SITE_FILES = ("index.html", "studio.css", "studio.js", "rig.js", "meraki.js", "wasi.js", "machine.js", "bezel.js")
WASM_FLAGS = ["-target", "wasm32-wasi", "-DMERAKIPLUS_WASM", "-mexec-model=reactor", "-O2", "-s"]
WASM_LIBS = ["-lm", "-lwasi-emulated-signal", "-lwasi-emulated-mman", "-lwasi-emulated-process-clocks",
             "-lwasi-emulated-getpid"]


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode != 0:
        sys.stderr.write(r.stdout + r.stderr)
        raise SystemExit(f"build.py: failed: {' '.join(map(str, cmd))}")
    return r.stdout


# ------------------------------------------------------------------ backport (refs older than MERAKIPLUS_WASM)
MAIN_HEAD = "int main(int argc,char**argv){\n    signal(SIGINT,onsig); signal(SIGTERM,onsig);\n    NET_CLI(argc,argv)\n"
LOOP_HEAD = "    while(run){\n        ms_t now=now_ms();\n"
LOOP_SLEEP = "        struct timespec sl={0, 2*1000*1000}; nanosleep(&sl,NULL);\n    }\n"
MAIN_TAIL = "    return MAIN_RC;\n}\n"


def backport(src: Path):
    """Make an old src/ tree build with -DMERAKIPLUS_WASM. Its UI code is not changed: main()'s own startup and loop body
    become the two fragments wasm_hal.c includes; main() itself is only excluded from the browser build."""
    uni = src / "merakiplus.c"
    text = uni.read_text()
    if "MERAKIPLUS_WASM" in text:
        return False
    mp = src / "mp"
    mp.mkdir(exist_ok=True)
    host = None                                  # the file that holds the device/SIM main() (monolithic or src/mp/main.c)
    for f in [uni] + sorted(mp.glob("*.c")):
        if MAIN_HEAD in f.read_text():
            host = f
            break
    if host is None:
        raise SystemExit("build.py: backport: no device/SIM main() of the expected shape in this ref")
    h = host.read_text()
    a = h.index(MAIN_HEAD)
    s0 = a + len(MAIN_HEAD)
    s1 = h.index(LOOP_HEAD, s0)
    b0 = s1 + len(LOOP_HEAD)
    b1 = h.index(LOOP_SLEEP, b0)
    end = h.index(MAIN_TAIL, b1) + len(MAIN_TAIL)
    note = "/* generated by sim/studio/build.py (backport): verbatim from this ref's main() */\n"
    (mp / "main_setup.c").write_text(note + h[s0:s1])
    (mp / "main_step.c").write_text(note + h[b0:b1])
    inc = "mp/wasm_hal.c" if host == uni else "wasm_hal.c"
    h = (h[:a] + "#ifndef MERAKIPLUS_WASM\n" + h[a:end] + "#endif\n#ifdef MERAKIPLUS_WASM\n#include \"" + inc + "\"\n#endif\n"
         + h[end:])
    host.write_text(h)
    text = uni.read_text()
    marker = "#define _GNU_SOURCE\n"
    if marker not in text:
        raise SystemExit("build.py: backport: no '#define _GNU_SOURCE' in merakiplus.c")
    text = text.replace(marker, marker + '#ifdef MERAKIPLUS_WASM\n#include "mp/wasm_compat.h"\n#endif\n', 1)
    uni.write_text(text)
    for name in ("wasm_compat.h", "wasm_hal.c"):
        shutil.copy2(ROOT / "src" / "mp" / name, mp / name)
    return True


def version_of(src: Path):
    m = re.search(r'#define MERAKIPLUS_VERSION "([^"]+)"', (src / "merakiplus.c").read_text())
    return m.group(1) if m else "?"


def build_wasm(src: Path, out: Path):
    out.parent.mkdir(parents=True, exist_ok=True)
    run(["zig", "cc", *WASM_FLAGS, "-o", str(out), str(src / "merakiplus.c"), *WASM_LIBS])
    return out.stat().st_size


def git(*args):
    return run(["git", "-C", str(ROOT), *args]).strip()


def extract_ref(ref: str, dest: Path):
    data = subprocess.run(["git", "-C", str(ROOT), "archive", "--format=tar", ref, "src"], capture_output=True)
    if data.returncode != 0:
        raise SystemExit(f"build.py: git archive {ref} failed (is the ref fetched? CI: fetch-depth 0):\n"
                         + data.stderr.decode(errors="replace"))
    with tarfile.open(fileobj=io.BytesIO(data.stdout)) as t:
        kw = {"filter": "data"} if hasattr(tarfile, "data_filter") else {}   # py3.12+: no absolute paths / links out
        t.extractall(dest, **kw)
    return dest / "src"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", default=str(ROOT / "build" / "studio"), help="output dir (default build/studio)")
    ap.add_argument("--classic-ref", default="c9a8524", help="git ref for the 'classic' build (default c9a8524 = v6.19)")
    ap.add_argument("--no-classic", action="store_true", help="build only the current tree")
    ap.add_argument("--quiet", action="store_true")
    a = ap.parse_args()
    out = Path(a.out).resolve()
    say = (lambda *x: None) if a.quiet else (lambda *x: print("studio:", *x, flush=True))
    if not shutil.which("zig"):
        raise SystemExit("build.py: zig not found (https://ziglang.org/download/ — 0.17.1)")
    out.mkdir(parents=True, exist_ok=True)
    builds = {}
    try:
        head = git("rev-parse", "--short", "HEAD")
        dirty = bool(git("status", "--porcelain", "--", "src"))
        branch = git("rev-parse", "--abbrev-ref", "HEAD")
    except SystemExit:
        head, dirty, branch = "?", False, "?"
    say(f"current: src/ of {branch}@{head}{' (+ local changes)' if dirty else ''}")
    n = build_wasm(ROOT / "src", out / "wasm" / "current.wasm")
    builds["current"] = {"label": "current", "ref": f"{branch}@{head}" + ("+dirty" if dirty else ""),
                         "version": version_of(ROOT / "src"), "wasm": "wasm/current.wasm", "bytes": n}
    if not a.no_classic:
        with tempfile.TemporaryDirectory(prefix="studio-classic-") as td:
            src = extract_ref(a.classic_ref, Path(td))
            bp = backport(src)
            say(f"classic: src/ of {a.classic_ref}{' (backported)' if bp else ''}")
            n = build_wasm(src, out / "wasm" / "classic.wasm")
            try:
                desc = git("log", "-1", "--format=%h %s", a.classic_ref)
            except SystemExit:
                desc = a.classic_ref
            builds["classic"] = {"label": "classic", "ref": a.classic_ref, "desc": desc, "version": version_of(src),
                                 "wasm": "wasm/classic.wasm", "bytes": n, "backported": bp}
    elif (out / "wasm" / "classic.wasm").exists():
        (out / "wasm" / "classic.wasm").unlink()
    for name in SITE_FILES:
        if (HERE / name).exists():
            shutil.copy2(HERE / name, out / name)
    (out / "fixtures").mkdir(exist_ok=True)
    for name in ("config.json", "parity_spec.json"):
        shutil.copy2(ROOT / "sim" / "fixtures" / name, out / "fixtures" / name)
    (out / "builds.json").write_text(json.dumps(builds, indent=1) + "\n")
    for k, b in builds.items():
        say(f"  {k:8s} {b['version']:6s} {b['bytes'] / 1024:7.1f} KiB  wasm/{k}.wasm")
    say(f"site -> {out}")


if __name__ == "__main__":
    main()
